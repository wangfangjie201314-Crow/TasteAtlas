"""Operator-only, one-time transfer of an existing stopped SQLite review ledger.

No credentials on the command line, no new allowance, no overwrite or retry.
Stop the old server and tunnel before invoking; do not restart the old copy.
"""
import argparse
from contextlib import closing
import hashlib
import os
from pathlib import Path
import sqlite3

from .postgres import connection_options, private_connection, validate_ledger


def migrate(database, database_url, *, source_stopped=False):
    if not source_stopped:
        raise ValueError('Stop the old service and tunnel and preserve a backup before transfer.')
    database = Path(database)
    if not database.is_absolute() or not database.is_file() or database.is_symlink():
        raise ValueError('An existing private absolute SQLite ledger is required.')
    before = hashlib.sha256(database.read_bytes()).hexdigest()
    with closing(sqlite3.connect(database.as_uri() + '?mode=ro', uri=True)) as source:
        if source.execute('PRAGMA journal_mode').fetchone()[0] != 'delete':
            raise ValueError('Transfer requires a stopped, checkpointed DELETE-mode SQLite ledger.')
        source.execute('BEGIN')
        if source.execute('PRAGMA integrity_check').fetchall() != [('ok',)]:
            raise ValueError('The existing SQLite ledger is invalid.')
        budget = source.execute('SELECT id, cap FROM budget').fetchall()
        calls = source.execute('SELECT id, started, path FROM calls ORDER BY id').fetchall()
        profiles = source.execute('SELECT ref, expires, state, payload FROM profiles ORDER BY ref').fetchall()
        if budget != [(1, 12)] or not 1 <= len(calls) <= 12:
            raise ValueError('Transfer requires the existing, consumed 12-call review allowance.')
    if hashlib.sha256(database.read_bytes()).hexdigest() != before:
        raise ValueError('The source changed; transfer refused. Stop its writer first.')
    with private_connection(connection_options(database_url)) as target:
        # Serializes competing transfers before checking the dedicated database.
        target.execute('SELECT pg_advisory_xact_lock(81970012)')
        other_schema = target.execute("""SELECT 1 FROM pg_namespace
            WHERE nspname NOT IN ('public','information_schema') AND nspname !~ '^pg_' LIMIT 1""").fetchone()
        user_object = target.execute("""SELECT 1 FROM pg_depend d JOIN pg_namespace n ON n.oid=d.refobjid
            WHERE d.refclassid='pg_namespace'::regclass
            AND n.nspname <> 'information_schema' AND n.nspname !~ '^pg_' LIMIT 1""").fetchone()
        if other_schema or user_object:
            raise ValueError('The PostgreSQL target must be empty; existing data will not be overwritten.')
        target.execute('CREATE TABLE budget (id INTEGER PRIMARY KEY CHECK(id=1), cap INTEGER NOT NULL CHECK(cap=12))')
        target.execute('CREATE TABLE calls (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, started DOUBLE PRECISION NOT NULL, path TEXT NOT NULL)')
        target.execute('CREATE TABLE profiles (ref TEXT PRIMARY KEY, expires DOUBLE PRECISION NOT NULL, state TEXT NOT NULL, payload TEXT NOT NULL)')
        target.execute('INSERT INTO budget VALUES (%s,%s)', budget[0])
        for row in calls:
            target.execute('INSERT INTO calls(id,started,path) VALUES(%s,%s,%s)', row)
        for row in profiles:
            target.execute('INSERT INTO profiles VALUES(%s,%s,%s,%s)', row)
        target.execute("SELECT setval(pg_get_serial_sequence('calls','id'), %s, true)", (max(row[0] for row in calls),))
        validate_ledger(target)
        if [tuple(row.values()) for row in target.execute('SELECT id,started,path FROM calls ORDER BY id').fetchall()] != calls:
            raise ValueError('The transferred request ledger does not match the source.')
        if [tuple(row.values()) for row in target.execute('SELECT ref,expires,state,payload FROM profiles ORDER BY ref').fetchall()] != profiles:
            raise ValueError('The transferred profile state does not match the source.')
        if hashlib.sha256(database.read_bytes()).hexdigest() != before:
            raise ValueError('The source changed during transfer; the target transaction was rolled back.')
    return {'used': len(calls), 'limit': 12, 'profiles': len(profiles), 'source_sha256': before}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('sqlite_ledger', type=Path)
    parser.add_argument('--source-stopped', action='store_true')
    args = parser.parse_args()
    try:
        result = migrate(args.sqlite_ledger, os.environ.get('TASTEATLAS_DATABASE_URL', ''),
                         source_stopped=args.source_stopped)
        print('Transferred the existing ledger: {used}/{limit}; no new allowance created.'.format(**result))
    except Exception as error:
        print('Transfer refused or failed ({0}); no automatic retry.'.format(type(error).__name__))
        raise SystemExit(1)
